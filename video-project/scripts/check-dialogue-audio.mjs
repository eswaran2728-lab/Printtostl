#!/usr/bin/env node
// Detects which of the replacement-dialogue WAV files are REAL recordings
// vs the silent placeholders this project ships with, so the composition
// can automatically fall back to the original source narration wherever a
// real replacement hasn't been supplied yet. Run this any time you drop in
// a new WAV — then re-render. (Also run automatically before render via
// `npm run prerender`, if wired into package.json.)
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const FF = path.join(ROOT, "node_modules/@remotion/compositor-linux-x64-gnu/ffmpeg");
const DIALOGUE_DIR = path.join(ROOT, "public/audio/dialogue");

const FILES = [
  "female-replacement-01.wav",
  "female-replacement-02.wav",
  "female-replacement-03.wav",
  "female-replacement-04.wav",
  "female-replacement-05.wav",
  "female-replacement-06.wav",
  "female-replacement-07.wav",
];

// Silent placeholders read as -91dB (digital silence). Anything louder than
// -50dB mean volume is treated as real recorded speech.
const SILENCE_THRESHOLD_DB = -50;

function meanVolumeDb(filePath) {
  const out = execFileSync(FF, ["-i", filePath, "-af", "volumedetect", "-f", "null", "-"], {
    encoding: "utf-8",
    stdio: ["ignore", "pipe", "pipe"],
  }).toString();
  return out;
}

const availability = {};
for (const file of FILES) {
  const filePath = path.join(DIALOGUE_DIR, file);
  if (!existsSync(filePath)) {
    availability[file] = false;
    continue;
  }
  let stderr = "";
  try {
    execFileSync(FF, ["-i", filePath, "-af", "volumedetect", "-f", "null", "-"], {
      stdio: ["ignore", "ignore", "pipe"],
    });
  } catch (e) {
    stderr = e.stderr ? e.stderr.toString() : "";
  }
  const match = stderr.match(/mean_volume:\s*(-?[\d.]+)\s*dB/);
  const meanDb = match ? parseFloat(match[1]) : -91;
  availability[file] = meanDb > SILENCE_THRESHOLD_DB;
}

const outPath = path.join(ROOT, "src/data/audioAvailability.generated.ts");
const body = `// AUTO-GENERATED by scripts/check-dialogue-audio.mjs — do not hand-edit.
// Re-run that script after dropping a new WAV into public/audio/dialogue/
// and re-render. true = real recorded speech detected (mean volume above
// ${SILENCE_THRESHOLD_DB}dB); false = silent placeholder or missing file,
// meaning the composition falls back to the original source narration for
// that line's time range.
export const DIALOGUE_AUDIO_AVAILABLE: Record<string, boolean> = ${JSON.stringify(
  availability,
  null,
  2
)};
`;
writeFileSync(outPath, body);
console.log("Wrote", outPath);
console.log(availability);
